const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
for(const m of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))if(m[1].trim())new vm.Script(m[1]);
const all={id:'m1',category:'makeup',description:'문법 보강 [대상:all]'};
const hb={id:'m2',category:'makeup',description:'[대상:sc_hanbaek]'};
const cls={id:'m3',category:'makeup',description:'[대상:chidong_sat_1800]'};
const review={id:'r1',category:'review',description:''};
const ctx={db:{videos:[all,hb,cls,review]}};vm.createContext(ctx);
const start=html.indexOf('const MAKEUP_SCHOOLS='),end=html.indexOf('function clinicVideoSchool');
const classes=html.slice(html.indexOf('var STUDENT_CLASSES='),html.indexOf('function studentClassLabel'));
vm.runInContext(classes+html.slice(start,end),ctx);
const seen=s=>ctx.makeupVideos().filter(v=>ctx.makeupVideoForStudent(v,s)).map(v=>v.id);
assert.deepEqual(seen({school_id:'sc_hanbaek',group_id:'hanbaek_sat_1030'}),['m1','m2']);
assert.deepEqual(seen({school_id:'sc_chidong',group_id:'chidong_sat_1800'}),['m1','m3']);
assert.deepEqual(seen({school_id:'sc_chidong',group_id:'chidong_sun_1430'}),['m1'],'other class stays hidden');
assert.equal(ctx.makeupVideoForStudent(review,{school_id:'sc_hanbaek'}),false);
assert.equal(ctx.makeupVideoDescription(all),'문법 보강');
assert.equal(ctx.makeupVideoTarget({description:'설명만'}),'all');
assert.match(html,/v\.category==='makeup'&&!makeupVideoForStudent\(v,session\)/,'openPlay gate');
assert.match(html,/sNav\('makeup'\)/);
console.log('PASS: makeup videos shown only to their school/class; inline JS valid.');
