// Run with PGLITE_PATH pointing to an installed @electric-sql/pglite package.
const {PGlite}=require(process.env.PGLITE_PATH||'@electric-sql/pglite');
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {complete,progress,parseQuestions}=require('../weekly-homework.js');
(async()=>{
 const db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create schema extensions;create schema storage;
 create table users(id text primary key,name text,role text,status text,group_id text);
 create table exams(id text primary key,name text,category text);
 create table qa_weeks(id text primary key);
 create table videos(id text primary key);
 create table progress(student_id text,video_id text,percent int);
 create table vocab_responses(student_id text,student_name text,unit_week int);
 create table exam_responses(student_id text,student_name text,exam_id text);
 create table qa_questions(student_id text,week_id text,prob_num text,category text,question text);
 create table study_sessions(student_id text,start_time timestamptz,end_time timestamptz,start_photo_url text,end_photo_url text);
 create table storage.objects(bucket_id text,name text);
 create function authenticate_user(p_id text,p_password text,p_role text) returns jsonb language sql as $$ select to_jsonb(u) from users u where id=p_id and role=p_role and p_password='test-only' $$;
 insert into users values ('t','교사','teacher','active',''),('s','학생','student','active','class'),('other','다른 학생','student','active','other'),('pending','대기','student','pending','class');
 insert into exams values('e','필수 과제','homework');insert into qa_weeks values('q');insert into videos values('v');`);
 await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations/20260906090000_weekly_homework.sql'),'utf8'));
 const rpc=async(id,role,action,payload,password='test-only')=>(await db.query('select weekly_homework_rpc($1,$2,$3,$4,$5::jsonb) as data',[id,password,role,action,JSON.stringify(payload)])).rows[0].data;
 const cfg={exam_ids:['e'],vocab_units:[1],qa_week_id:'q',video_id:'v',questions:[{prompt:'실제 수업 문항',answer:'O',explanation:'해설'}],question_target:5,study_count:2,study_minutes:40};
 const payload={week_start:'2026-09-07',group_id:'class',title:'9월 필수 과제',config:cfg};
 await assert.rejects(rpc('s','student','create',payload));
 await assert.rejects(rpc('t','teacher','create',payload,'wrong'));
 const {id}=await rpc('t','teacher','create',payload);
 await rpc('t','teacher','update',{...payload,plan_id:id,title:'수정한 필수 과제'});
 await assert.rejects(rpc('t','teacher','create',payload),'one plan per class/week');
 await assert.rejects(rpc('pending','student','list',{week_start:'2026-09-07'}));
 assert.deepEqual(await rpc('other','student','list',{week_start:'2026-09-07'}),[]);
 let student=(await rpc('s','student','list',{week_start:'2026-09-07'}))[0];
 assert.equal(student.config.questions[0].answer,undefined,'hide answer key before submission');
 assert.equal(complete(student.students[0]),false);
 await db.exec(`insert into vocab_responses values ('s','학생',1);insert into exam_responses values('s','학생','e');
 insert into qa_questions select 's','q',n::text,'','질문 내용' from generate_series(1,5)n;
 insert into qa_questions values('s','q','1','','중복 질문');
 insert into study_sessions values
 ('s','2026-09-07 10:00+09','2026-09-07 10:39:59+09','start','end'),
 ('s','2026-09-08 10:00+09','2026-09-08 10:40+09','start','end'),
 ('s','2026-09-06 10:00+09','2026-09-06 10:50+09','start','end'),
 ('s','2026-09-09 10:00+09',null,'start',null);`);
 student=(await rpc('s','student','list',{week_start:'2026-09-07'}))[0];
 assert.equal(student.students[0].states.study.done,1,'40-minute boundary, week boundary, and end-photo checks');
 assert.equal(student.students[0].states.qa.done,5,'duplicate question numbers do not count twice');
 await assert.rejects(rpc('other','student','concept',{plan_id:id,answers:['O']}));
 await assert.rejects(rpc('s','student','concept',{plan_id:id,answers:[]}));
 assert.equal((await rpc('s','student','concept',{plan_id:id,answers:['X']})).score,0);
 student=(await rpc('s','student','list',{week_start:'2026-09-07'}))[0];
 assert.equal(student.students[0].states.concept.status,'retry');
 await rpc('s','student','concept',{plan_id:id,answers:['O']});
 await assert.rejects(rpc('t','teacher','update',{...payload,plan_id:id,config:{...cfg,questions:[{prompt:'다른 문항',answer:'X'}]}}),'submitted OX must retain its grading key');
 const photo='weekly-notes/s/'+id+'/photo.jpg';
 await db.query('insert into storage.objects values ($1,$2)',['exam-photos',photo]);
 await assert.rejects(rpc('s','student','notebook',{plan_id:id,mode:'home',photos:[photo]}),'home submission requires full video');
 await db.exec("insert into progress values('s','v',100)");
 await rpc('s','student','notebook',{plan_id:id,mode:'home',photos:[photo]});
 student=(await rpc('s','student','list',{week_start:'2026-09-07'}))[0];
 assert.equal(student.students[0].states.notebook.status,'pending');
 assert.equal(complete(student.students[0]),false,'pending photos are not complete');
 await assert.rejects(rpc('s','student','review',{plan_id:id,student_id:'s',status:'approved'}));
 await rpc('t','teacher','review',{plan_id:id,student_id:'s',status:'rejected',feedback:'다시 촬영'});
 await rpc('s','student','notebook',{plan_id:id,mode:'clinic',photos:[photo]});
 await rpc('t','teacher','review',{plan_id:id,student_id:'s',status:'approved'});
 await db.exec("insert into study_sessions values('s','2026-09-10 10:00+09','2026-09-10 10:40+09','start','end')");
 student=(await rpc('s','student','list',{week_start:'2026-09-07'}))[0];
 const teacher=(await rpc('t','teacher','list',{week_start:'2026-09-07'}))[0];
 assert.deepEqual(student.students[0].states,teacher.students[0].states,'teacher and student share all statuses');
 assert.equal(progress(student.students[0]),6);assert.equal(complete(student.students[0]),true);
 assert.equal(teacher.config.questions[0].answer,'O');
 await db.exec('set role anon');
 await assert.rejects(db.query('select * from weekly_homework'),'direct anonymous reads forbidden');
 await db.exec('reset role');
 await db.exec('alter table qa_questions drop column category');
 const legacy=(await rpc('s','student','list',{week_start:'2026-09-07'}))[0];
 assert.equal(legacy.students[0].states.qa.status,'done','production schema without optional category works');
 assert.throws(()=>parseQuestions('문항 | A | 해설'));
 assert.equal(parseQuestions('문항 | O | 해설')[0].answer,'O');
 await db.close();console.log('PASS: real PostgreSQL migration/RPC, authorization, 6-task completion, 40-minute boundary, distinct questions, photos, OX retries, shared statuses');
})().catch(e=>{console.error(e);process.exitCode=1;});
